// Build the Sunburst courtyard-view panorama assets + manifest.
//
// Source: a "Rivali Tiower 1" folder of <Floor>/Apartment/<nnn>/ directories,
// each holding several drone frames plus one wide "*_stitch.jpg" panorama.
//
// WHY THIS DIFFERS FROM THE OTHER TWO BUILDERS
// --------------------------------------------
// Stargaze and Moonrise name the apartment inside the filename, so those
// scripts read it from there. Sunburst's filenames can't be trusted:
//
//   2nd. Floor/Apartment/101/DJI_0030_1st Floor_Apt 101_stitch.jpg   <- says 1st
//   3rd. Floor/Apartment/103/DJI__0008_3rd Floor_Apt_103-104_stitch.jpg
//   3rd. Floor/Apartment/104/DJI__0008_3rd Floor_Apt_103-104_stitch.jpg
//   13th. Floor/Apartment/104/DJI_0027_13th Floor_Apt_104.jpg_stitch.jpg
//
// ...a stale floor label, one shot named for two apartments, and a doubled
// extension. Checksums settle it: the 1st- and 2nd-floor "101" files are
// DIFFERENT images despite the identical name, so the folder is right and the
// filename is stale. The 3rd/6th floor "103-104" pairs genuinely are the same
// image in both folders — one shot covering two apartments, which is the
// photographer's intent and is kept for both.
//
// So the FOLDER PATH is the source of truth here: floor from "<n>th. Floor",
// apartment position from "Apartment/1<nn>" (101 -> unit 1 ... 108 -> unit 8).
// The apartment number the app uses is floor*100 + position, matching the other
// towers.
//
// Usage: node scripts/build-sunburst-views.mjs ["/path/to/Rivali Tiower 1"]
import sharp from 'sharp'
import { readdirSync, statSync, rmSync, mkdirSync, writeFileSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = dirname(HERE)
const DEFAULT_SRC = '/Users/Arsalan/Downloads/Rivali Tiower 1'
const OUT_DIR = join(ROOT, 'public', 'unit', 'views', 'sunburst')
const MANIFEST = join(ROOT, 'src', 'data', 'sunburstViews.js')
const TARGET_H = 1440 // output height in px (full-screen panorama)
const WEBP_QUALITY = 85 // high quality, re-encoded from the original source

// "13th. Floor" / "1st Floor" / "2nd. Floor" -> 13 / 1 / 2
const floorOf = (name) => {
  const m = /^(\d+)\s*(?:st|nd|rd|th)?\.?\s*floor/i.exec(name.trim())
  return m ? Number(m[1]) : null
}

// "104" -> 4. The shoot labels apartments 101-108 on every floor, so the
// position is simply the folder number less 100.
const positionOf = (name) => {
  const n = Number(name.trim())
  return Number.isInteger(n) && n > 100 && n < 200 ? n - 100 : null
}

const isStitch = (f) => /stitch/i.test(f) && /\.jpe?g$/i.test(f)

const main = async () => {
  const src = process.argv[2] || DEFAULT_SRC
  if (!statSync(src, { throwIfNoEntry: false })?.isDirectory()) {
    console.error(`Source folder not found: ${src}`)
    process.exit(1)
  }

  rmSync(OUT_DIR, { recursive: true, force: true })
  mkdirSync(OUT_DIR, { recursive: true })

  const available = []
  const skipped = []

  for (const floorDir of readdirSync(src).sort()) {
    const floor = floorOf(floorDir)
    const aptRoot = join(src, floorDir, 'Apartment')
    if (floor == null || !statSync(aptRoot, { throwIfNoEntry: false })?.isDirectory()) {
      if (floor == null && statSync(join(src, floorDir), { throwIfNoEntry: false })?.isDirectory())
        skipped.push([floorDir, 'not a "<n>th. Floor" directory'])
      continue
    }

    for (const aptDir of readdirSync(aptRoot).sort()) {
      const dir = join(aptRoot, aptDir)
      if (!statSync(dir, { throwIfNoEntry: false })?.isDirectory()) continue
      const position = positionOf(aptDir)
      if (position == null) {
        skipped.push([`${floorDir}/${aptDir}`, 'apartment folder is not 1nn'])
        continue
      }
      const stitches = readdirSync(dir).filter(isStitch).sort()
      if (!stitches.length) continue // nothing shot for this apartment

      const apt = floor * 100 + position
      await sharp(join(dir, stitches[0]))
        .resize({ height: TARGET_H, withoutEnlargement: true, kernel: 'lanczos3' })
        .webp({ quality: WEBP_QUALITY })
        .toFile(join(OUT_DIR, `${apt}.webp`))
      available.push(apt)
      console.log(`  ${apt}  <-  ${floorDir}/Apartment/${aptDir}/${stitches[0]}`)
    }
  }

  available.sort((a, b) => a - b)
  writeManifest(available)

  console.log(`\nWrote ${available.length} panoramas (WebP q${WEBP_QUALITY}) to ${OUT_DIR}`)
  console.log(`Manifest: ${MANIFEST}`)
  if (skipped.length) {
    console.log(`\nSkipped ${skipped.length} entr(y/ies):`)
    skipped.forEach(([f, why]) => console.log(`  ${f}: ${why}`))
  }
}

const writeManifest = (available) => {
  const body =
    `// AUTO-GENERATED by scripts/build-sunburst-views.mjs — do not edit by hand.\n` +
    `// Sunburst apartments (floor*100 + unit-position) that have a courtyard\n` +
    `// panorama. Apartments without one are absent, so they're hidden from the\n` +
    `// floor dropdown in the apartment view.\n` +
    `export const SUNBURST_VIEW_APTS = [${available.join(', ')}]\n\n` +
    `const VIEW_SET = new Set(SUNBURST_VIEW_APTS)\n\n` +
    `// Apartment number for a floor + unit position (1-8).\n` +
    `export const aptNumber = (floor, position) => floor * 100 + position\n\n` +
    `// Public path to a panorama, or null when that apartment has no view.\n` +
    `export const viewImage = (floor, position) =>\n` +
    `  VIEW_SET.has(aptNumber(floor, position))\n` +
    `    ? \`/unit/views/sunburst/\${aptNumber(floor, position)}.webp\`\n` +
    `    : null\n\n` +
    `// Floors (ascending) where the given unit position has a panorama.\n` +
    `export const floorsForPosition = (position) =>\n` +
    `  SUNBURST_VIEW_APTS.filter((a) => a % 100 === position).map((a) =>\n` +
    `    Math.floor(a / 100),\n` +
    `  )\n`
  mkdirSync(dirname(MANIFEST), { recursive: true })
  writeFileSync(MANIFEST, body)
}

main()

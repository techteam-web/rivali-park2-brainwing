// Builds a 1920-class copy of every amenity slide background and writes the
// srcset manifest the hotspot pages read (src/data/hotspotBgSrcSet.js).
//
// Run after adding or replacing a slide background:
//   node scripts/build-hotspot-variants.mjs
//
// The slides are object-cover over a stage of max(100vw, 100vh * 1440/1024),
// so what matters is how wide a stage an image can cover, not its raw width:
// a wide image runs out of height first. Each candidate is described by that
// cover width, so the browser picks the smallest file that still fills the
// screen at its pixel ratio. Backgrounds with no entry just use their src.
import sharp from 'sharp'
import fs from 'node:fs'
import path from 'node:path'

const ROOT = 'public/gallery/hotspots'
const STAGE_RATIO = 1440 / 1024
const SMALL_W = 1920
// One px of headroom so resize rounding can't leave the copy a pixel short
// of a 1920 stage (it would then lose to the full file on 1080p screens).
const SMALL_H = Math.ceil(SMALL_W / STAGE_RATIO) + 1

const coverWidth = (w, h) => Math.round(Math.min(w, h * STAGE_RATIO))
const url = (p) => encodeURI('/' + path.relative('public', p).split(path.sep).join('/'))

const manifest = {}
for (const dir of fs.readdirSync(ROOT, { withFileTypes: true })) {
  if (!dir.isDirectory()) continue
  for (const f of fs.readdirSync(path.join(ROOT, dir.name))) {
    if (!f.endsWith(' bg.webp')) continue
    const src = path.join(ROOT, dir.name, f)
    const { width, height } = await sharp(src).metadata()
    const full = coverWidth(width, height)
    if (full <= SMALL_W * 1.15) continue
    const small = src.replace(/\.webp$/, '@1920.webp')
    const info = await sharp(src)
      .resize(SMALL_W, SMALL_H, { fit: 'outside' })
      .webp({ quality: 82, effort: 6 })
      .toFile(small)
    const key = '/' + path.relative('public', src).split(path.sep).join('/')
    manifest[key] = `${url(small)} ${coverWidth(info.width, info.height)}w, ${url(src)} ${full}w`
    console.log(`${key}  ${(fs.statSync(src).size / 1024) | 0}KB -> ${(info.size / 1024) | 0}KB`)
  }
}

const out = `// Generated by scripts/build-hotspot-variants.mjs; do not edit by hand.
// Maps a slide background to its srcset (see that script for how the
// candidates are described).
const SRCSETS = ${JSON.stringify(manifest, null, 2)}

// Stage width the slide backgrounds cover: max(100vw, 100vh * 1440/1024).
export const HOTSPOT_BG_SIZES = '(min-aspect-ratio: 1440/1024) 100vw, 140.625vh'

export const hotspotBgSrcSet = (bg) => SRCSETS[bg]
`
fs.writeFileSync('src/data/hotspotBgSrcSet.js', out)

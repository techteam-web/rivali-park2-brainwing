// Build the Skyleap apartment-view panorama assets + manifest.
//
// Source: a flat folder of stitched drone panoramas named
//   DJI_0316_8 Floor-1.png   (also seen as "8 Floor_2.png" — both separators)
// i.e. <sequence>_<floor> Floor-<view>, with FOUR views per floor.
//
// WHY THIS ONE MAPS VIEWS, NOT APARTMENTS
// ---------------------------------------
// The other towers shoot one panorama per apartment, so their manifests key on
// floor*100 + position. Skyleap was shot four times per floor — once per facade
// — and each panorama is shared by the TWO units that look that way:
//
//   view 1 -> units 1, 2   (top of the plate)
//   view 2 -> units 7, 8   (left)
//   view 3 -> units 5, 6   (bottom)
//   view 4 -> units 3, 4   (right)
//
// (Read around the floor plate, that's a rotation: top, left, bottom, right.)
//
// So the assets are stored per view — <floor>-<view>.webp — and the manifest
// maps a unit position to its view. Storing per apartment instead would write
// every image twice for no benefit.
//
// Usage: node scripts/build-skyleap-views.mjs ["/path/to/image"]
import sharp from 'sharp'
import { readdirSync, statSync, rmSync, mkdirSync, writeFileSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = dirname(HERE)
const DEFAULT_SRC = '/Users/Arsalan/Downloads/image'
const OUT_DIR = join(ROOT, 'public', 'unit', 'views', 'skyleap')
const MANIFEST = join(ROOT, 'src', 'data', 'skyleapViews.js')
const TARGET_H = 1440 // output height in px (full-screen panorama)
const WEBP_QUALITY = 85 // high quality, re-encoded from the original source

// "<n> Floor-<v>" or "<n> Floor_<v>" — the export uses both separators.
const NAME_RE = /_(\d+)\s*Floor[-_](\d)\.(?:png|jpe?g)$/i

const main = async () => {
  const src = process.argv[2] || DEFAULT_SRC
  if (!statSync(src, { throwIfNoEntry: false })?.isDirectory()) {
    console.error(`Source folder not found: ${src}`)
    process.exit(1)
  }

  rmSync(OUT_DIR, { recursive: true, force: true })
  mkdirSync(OUT_DIR, { recursive: true })

  const byFloor = new Map()
  const skipped = []

  for (const file of readdirSync(src).sort()) {
    if (!/\.(png|jpe?g)$/i.test(file)) continue
    const m = NAME_RE.exec(file)
    if (!m) {
      skipped.push([file, 'not "<floor> Floor-<view>"'])
      continue
    }
    const floor = Number(m[1])
    const view = Number(m[2])
    if (view < 1 || view > 4) {
      skipped.push([file, `view ${view} outside 1-4`])
      continue
    }

    // The stitches carry an alpha channel but are fully opaque; flatten so the
    // WebP has no needless alpha plane.
    await sharp(join(src, file))
      .flatten({ background: '#000000' })
      .resize({ height: TARGET_H, withoutEnlargement: true, kernel: 'lanczos3' })
      .webp({ quality: WEBP_QUALITY })
      .toFile(join(OUT_DIR, `${floor}-${view}.webp`))

    if (!byFloor.has(floor)) byFloor.set(floor, new Set())
    byFloor.get(floor).add(view)
    console.log(`  ${floor}-${view}  <-  ${file}`)
  }

  const floors = [...byFloor.keys()].sort((a, b) => a - b)
  writeManifest(floors.map((f) => [f, [...byFloor.get(f)].sort()]))

  const total = floors.reduce((n, f) => n + byFloor.get(f).size, 0)
  console.log(`\nWrote ${total} panoramas across ${floors.length} floors to ${OUT_DIR}`)
  console.log(`Manifest: ${MANIFEST}`)
  const partial = floors.filter((f) => byFloor.get(f).size < 4)
  if (partial.length)
    console.log(
      `\nFloors still missing views: ` +
        partial.map((f) => `${f} (has ${[...byFloor.get(f)].sort().join(',')})`).join(', '),
    )
  if (skipped.length) {
    console.log(`\nSkipped ${skipped.length} file(s):`)
    skipped.forEach(([f, why]) => console.log(`  ${f}: ${why}`))
  }
}

const writeManifest = (entries) => {
  const table = entries.map(([f, vs]) => `  ${f}: [${vs.join(', ')}],`).join('\n')
  const body =
    `// AUTO-GENERATED by scripts/build-skyleap-views.mjs — do not edit by hand.\n` +
    `//\n` +
    `// Skyleap was shot four times per floor, once per facade, and each\n` +
    `// panorama is shared by the two units that face that way. So the assets\n` +
    `// are keyed <floor>-<view> and a unit position resolves to its view.\n` +
    `//\n` +
    `// Floors without an entry (or missing a view) simply have no panorama, so\n` +
    `// those apartments fall through to the "coming soon" state.\n\n` +
    `// Unit position (1-8) -> which of the four facade views it looks out on.\n` +
    `export const VIEW_FOR_POSITION = {\n` +
    `  1: 1, 2: 1, // top of the floor plate\n` +
    `  7: 2, 8: 2, // left\n` +
    `  5: 3, 6: 3, // bottom\n` +
    `  3: 4, 4: 4, // right\n` +
    `}\n\n` +
    `// Floor -> the views actually shot on it.\n` +
    `export const SKYLEAP_VIEWS = {\n${table}\n}\n\n` +
    `// Public path to a panorama, or null when that apartment has no view.\n` +
    `export const viewImage = (floor, position) => {\n` +
    `  const view = VIEW_FOR_POSITION[position]\n` +
    `  return view && SKYLEAP_VIEWS[floor]?.includes(view)\n` +
    `    ? \`/unit/views/skyleap/\${floor}-\${view}.webp\`\n` +
    `    : null\n` +
    `}\n\n` +
    `// Floors (ascending) where the given unit position has a panorama.\n` +
    `export const floorsForPosition = (position) => {\n` +
    `  const view = VIEW_FOR_POSITION[position]\n` +
    `  if (!view) return []\n` +
    `  return Object.keys(SKYLEAP_VIEWS)\n` +
    `    .map(Number)\n` +
    `    .filter((f) => SKYLEAP_VIEWS[f].includes(view))\n` +
    `    .sort((a, b) => a - b)\n` +
    `}\n`
  mkdirSync(dirname(MANIFEST), { recursive: true })
  writeFileSync(MANIFEST, body)
}

main()

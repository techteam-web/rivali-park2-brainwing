// Build the Moonrise courtyard-view panorama assets + manifest.
//
// Source: a flat folder of stitched drone panoramas named like
//   DJI_0138_25th Floor_Apt_2505_stitch.jpg
// (mirrors scripts/build-views.mjs, but Moonrise's panoramas ship as one flat
// folder rather than the Stargaze <Floor>/Apartment/<apt>/ tree). Apartment
// numbers are floor*100 + position (e.g. 25th floor, position 5 -> 2505); the
// position (1-6) is the floor-plan unit number.
//
// For every "*_stitch.jpg" we:
//   1. parse the apartment number from the filename,
//   2. re-encode it FROM SOURCE to a TARGET_H-tall WebP (high quality, no
//      double-compression) at public/unit/views/moonrise/<apt>.webp,
//   3. record <apt> in the generated manifest (src/data/moonriseViews.js).
//
// Usage: node scripts/build-moonrise-views.mjs ["/path/to/Moonrise Tower - 3"]
import sharp from 'sharp'
import { readdirSync, statSync, rmSync, mkdirSync, writeFileSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = dirname(HERE)
const DEFAULT_SRC = 'C:/Users/arsal/Downloads/Moonrise Tower - 3'
const OUT_DIR = join(ROOT, 'public', 'unit', 'views', 'moonrise')
const MANIFEST = join(ROOT, 'src', 'data', 'moonriseViews.js')
const TARGET_H = 1440 // output height in px (full-screen panorama)
const WEBP_QUALITY = 85 // high quality, re-encoded from the original source

const APT_RE = /(?:Apt[_ ]+|_)(\d{3,4})_stitch/i

// Apartment number named inside a stitch filename, or null if generic.
const parseApt = (filename) => {
  const m = filename.match(APT_RE)
  return m ? Number(m[1]) : null
}

const main = async () => {
  const src = process.argv[2] || DEFAULT_SRC
  if (!statSync(src, { throwIfNoEntry: false })?.isDirectory()) {
    console.error(`Source folder not found: ${src}`)
    process.exit(1)
  }

  // Fresh output dir (drop any earlier renders).
  rmSync(OUT_DIR, { recursive: true, force: true })
  mkdirSync(OUT_DIR, { recursive: true })

  const available = []
  const skipped = []

  for (const file of readdirSync(src).sort()) {
    if (!/\.jpe?g$/i.test(file) || !/stitch/i.test(file)) continue
    const apt = parseApt(file)
    if (!apt) {
      skipped.push([file, 'no apartment number in filename'])
      continue
    }
    await sharp(join(src, file))
      .resize({ height: TARGET_H, withoutEnlargement: true, kernel: 'lanczos3' })
      .webp({ quality: WEBP_QUALITY })
      .toFile(join(OUT_DIR, `${apt}.webp`))
    available.push(apt)
    console.log(`  ${apt}  <-  ${file}`)
  }

  available.sort((a, b) => a - b)
  writeManifest(available)

  console.log(`\nWrote ${available.length} panoramas (WebP q${WEBP_QUALITY}) to ${OUT_DIR}`)
  console.log(`Manifest: ${MANIFEST}`)
  if (skipped.length) {
    console.log(`\nSkipped ${skipped.length} file(s):`)
    skipped.forEach(([f, why]) => console.log(`  ${f}: ${why}`))
  }
}

const writeManifest = (available) => {
  const apts = available.join(', ')
  const body =
    `// AUTO-GENERATED by scripts/build-moonrise-views.mjs — do not edit by hand.\n` +
    `// Moonrise apartments (floor*100 + unit-position) that have a courtyard\n` +
    `// panorama. Apartments without a panorama are absent, so they're hidden\n` +
    `// from the floor dropdown in the courtyard view.\n` +
    `export const MOONRISE_VIEW_APTS = [${apts}]\n\n` +
    `const VIEW_SET = new Set(MOONRISE_VIEW_APTS)\n\n` +
    `// Apartment number for a floor + unit position (1-6).\n` +
    `export const aptNumber = (floor, position) => floor * 100 + position\n\n` +
    `// Public path to a panorama, or null when that apartment has no view.\n` +
    `export const viewImage = (floor, position) =>\n` +
    `  VIEW_SET.has(aptNumber(floor, position))\n` +
    `    ? \`/unit/views/moonrise/\${aptNumber(floor, position)}.webp\`\n` +
    `    : null\n\n` +
    `// Floors (ascending) where the given unit position has a panorama.\n` +
    `export const floorsForPosition = (position) =>\n` +
    `  MOONRISE_VIEW_APTS.filter((a) => a % 100 === position).map((a) =>\n` +
    `    Math.floor(a / 100),\n` +
    `  )\n`
  mkdirSync(dirname(MANIFEST), { recursive: true })
  writeFileSync(MANIFEST, body)
}

main()
